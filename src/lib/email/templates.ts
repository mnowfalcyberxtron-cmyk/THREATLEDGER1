export function renderReviewVerdictEmail(props: {
  analystName: string;
  taskTitle: string;
  groupName: string;
  verdict: 'APPROVED' | 'CHANGES_REQUESTED' | 'REJECTED';
  reviewerName: string;
  comments?: string;
  taskUrl: string;
}): { subject: string; html: string } {
  const isApproved = props.verdict === 'APPROVED';
  const statusColor = isApproved ? '#10b981' : props.verdict === 'CHANGES_REQUESTED' ? '#f59e0b' : '#ef4444';
  const subject = `[Review Sign-off: ${props.verdict}] ${props.groupName}: ${props.taskTitle}`;

  const html = baseTemplate({
    headline: isApproved ? 'Research Report Approved' : 'Reviewer Feedback Received',
    bodyHtml: `
      <p>Analyst <strong>${props.analystName}</strong>,</p>
      <p>Reviewer <strong>${props.reviewerName}</strong> has completed the evaluation of your submitted intelligence deliverable:</p>
      <div class="card-box">
        <div class="card-row">
          <span class="card-label">Verdict:</span>
          <span class="card-value" style="color: ${statusColor}; font-size: 14px;">${props.verdict}</span>
        </div>
        <div class="card-row">
          <span class="card-label">Syndicate:</span>
          <span class="card-value">${props.groupName}</span>
        </div>
        <div class="card-row">
          <span class="card-label">Evaluator:</span>
          <span class="card-value">${props.reviewerName}</span>
        </div>
      </div>
      ${
        props.comments
          ? `<div style="background-color: #0f172a; border-left: 3px solid ${statusColor}; padding: 12px; border-radius: 4px; margin: 16px 0; font-size: 13px; color: #f1f5f9;">
               <strong>Reviewer Comments:</strong><br>
               <p style="margin-top: 6px; white-space: pre-wrap;">${props.comments}</p>
             </div>`
          : ''
      }
      <p>${
        isApproved
          ? 'Your report is now archived in the official CTI knowledge repository.'
          : 'Please address the requested modifications and submit a revised version.'
      }</p>
    `,
    ctaText: 'View Task in Workbench',
    ctaUrl: props.taskUrl,
  });

  return { subject, html };
}
